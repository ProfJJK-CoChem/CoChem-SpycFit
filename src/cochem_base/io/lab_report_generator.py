"""
Automated Publication-Ready Supporting Information (SI) & Lab Report Compiler.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from cochem_base.core.models import MolecularTopology, QCResultsRecord
from cochem_base.core.metadata import get_atomic_symbol
from cochem_base.io.reference_manager import ReferenceManager


class LabReportGenerator:
    """
    Assembles comprehensive FAIR-compliant Markdown, HTML, and LaTeX lab reports.
    """

    @classmethod
    def generate_jsonld_provenance(
        cls,
        topology: MolecularTopology,
        results: QCResultsRecord,
        method: str = "r2SCAN-3c",
    ) -> Dict[str, Any]:
        """Generate W3C PROV-O JSON-LD metadata block."""
        now = datetime.now(timezone.utc).isoformat()
        return {
            "@context": "https://www.w3.org/ns/prov-o.jsonld",
            "@type": "prov:Activity",
            "prov:startedAtTime": now,
            "prov:endedAtTime": now,
            "prov:used": {
                "@type": "cochem:MolecularTopology",
                "num_atoms": topology.num_atoms,
                "charge": topology.charge,
                "multiplicity": topology.multiplicity,
            },
            "prov:generated": {
                "@type": "cochem:QCResultsRecord",
                "energy_hartree": results.energy_hartree,
                "method": method,
            },
        }

    @classmethod
    def compile_markdown_si(
        cls,
        title: str,
        topology: MolecularTopology,
        results: QCResultsRecord,
        thermo_data: Optional[Dict[str, float]] = None,
        method: str = "r2SCAN-3c",
    ) -> str:
        """Compile journal-ready Markdown Supporting Information."""
        jsonld = cls.generate_jsonld_provenance(topology, results, method)
        coords_ang = topology.get_coordinates_angstrom()

        lines = [
            f"# Supporting Information: {title}",
            f"**Generated by CoChem-BASE on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}**",
            "",
            "## 1. Computational Methodology",
            f"Quantum chemistry calculations were executed using the `{method}` composite scheme. "
            "Thermochemical corrections were evaluated using the Grimme quasi-rigid rotor harmonic oscillator (qRRHO) approach.",
            "",
            "## 2. Optimized 3D Cartesian Coordinates (Angstroms)",
            "| Element | X | Y | Z |",
            "| :--- | :--- | :--- | :--- |",
        ]

        for idx, (z, (x, y, zc)) in enumerate(zip(topology.atomic_numbers, coords_ang)):
            sym = topology.symbols[idx] if topology.symbols else get_atomic_symbol(z)
            lines.append(f"| {sym} | {x:12.6f} | {y:12.6f} | {zc:12.6f} |")

        lines.extend([
            "",
            "## 3. Total Energies & Thermochemical Summary",
            f"- **Electronic Energy $E_{{\\text{{tot}}}}$**: `{results.energy_hartree:.8f} Hartree`",
        ])

        if results.rotational_constants_ghz:
            A, B, C = results.rotational_constants_ghz
            lines.append(f"- **Rotational Constants**: $A = {A:.4f}$, $B = {B:.4f}$, $C = {C:.4f}$ GHz")

        if thermo_data:
            lines.extend([
                f"- **Zero-Point Vibrational Energy (ZPVE)**: `{thermo_data.get('zpve_hartree', 0.0):.8f} Hartree` (`{thermo_data.get('zpve_kcal_mol', 0.0):.2f} kcal/mol`)",
                f"- **Total Entropy $S^\\circ_{{298}}$**: `{thermo_data.get('entropy_total_cal_mol_k', 0.0):.2f} cal/(mol*K)`",
                f"- **Total Enthalpy $H_{{298}}$**: `{thermo_data.get('enthalpy_hartree', 0.0):.8f} Hartree`",
                f"- **Gibbs Free Energy $G_{{298}}$**: `{thermo_data.get('gibbs_free_energy_hartree', 0.0):.8f} Hartree`",
            ])

        lines.extend([
            "",
            "## 4. W3C PROV-O FAIR Provenance Block",
            "```json",
            json.dumps(jsonld, indent=2),
            "```",
            "",
            "## 5. References",
            f"1. {ReferenceManager.format_acs('ORCA')}",
            f"2. {ReferenceManager.format_acs('r2SCAN-3c')}",
            f"3. {ReferenceManager.format_acs('Grimme-qRRHO')}",
            "",
        ])

        return "\n".join(lines) + "\n"
